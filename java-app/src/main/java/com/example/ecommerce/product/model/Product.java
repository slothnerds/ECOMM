package com.example.ecommerce.product.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.math.BigDecimal;
import java.time.Instant;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

/**
 * A catalog product, mapped to table ecomm.products (db/scripts/ecomm-setup.sql). The schema is
 * owned by that script; Hibernate only validates that this class matches it.
 *
 * <p>Equality is by {@code id} only (entity identity): two objects with the same id are the same
 * product, even if one has a newer price. Unsaved products (id null) are only equal to themselves.
 */
@Entity
@Table(name = "products")
@Getter
@Setter
@Builder(toBuilder = true)
// JPA needs a no-args constructor; Jackson also uses it (then setters) for JSON request bodies
@NoArgsConstructor
// Private: only the builder uses it. If public, Jackson 3 would build products from JSON through
// this constructor and pass null for fields missing from the JSON, skipping the defaults below.
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@ToString
public class Product {

  /** Generated by the database (GENERATED ALWAYS AS IDENTITY); null until saved. */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  /** Unique and fixed after creation. */
  @Column(nullable = false, updatable = false, length = 32)
  private String sku;

  @Column(nullable = false, length = 200)
  private String name;

  @Builder.Default
  @Column(nullable = false)
  private String description = "";

  /** Exact decimal amount; never use double for money (spec rule SN-3). */
  @Column(nullable = false, precision = 12, scale = 2)
  private BigDecimal price;

  /** Stored as text ('ACTIVE', ...), not as the enum's position. */
  @Builder.Default
  @Enumerated(EnumType.STRING)
  @Column(nullable = false, length = 20)
  private ProductStatus status = ProductStatus.ACTIVE;

  /** Category id; the Category entity and relationship come with categories in Stage 5. */
  @Column(name = "category_id")
  private Long categoryId;

  /** Set by Hibernate on insert. */
  @CreationTimestamp
  @Column(name = "created_at", nullable = false, updatable = false)
  private Instant createdAt;

  /** Set by Hibernate on every update. */
  @UpdateTimestamp
  @Column(name = "updated_at", nullable = false)
  private Instant updatedAt;

  /**
   * Optimistic locking: Hibernate adds "WHERE version = ?" to every UPDATE and increments it, so a
   * concurrent change makes the second update fail instead of silently overwriting the first.
   */
  @Version
  @Column(nullable = false)
  private Long version;

  /*
   * Written by hand instead of Lombok's @EqualsAndHashCode: Lombok would treat two unsaved
   * products (both ids null) as equal.
   */
  @Override
  public boolean equals(Object other) {
    if (this == other) {
      return true;
    }
    return other instanceof Product that && id != null && id.equals(that.id);
  }

  /** Constant per class, so the hash doesn't change when the id is assigned on save. */
  @Override
  public int hashCode() {
    return Product.class.hashCode();
  }
}
